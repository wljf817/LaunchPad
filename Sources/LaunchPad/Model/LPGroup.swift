import Foundation
import SQLite3

/// A folder. Its children are pages, each holding the folder's apps.
///
/// Children change only through the KVC array `children` (key `synthesizedChildren`): the four
/// accessor methods below keep the parent links and write each change to the database.
@objc(LPGroup)
class LPGroup: LPItem, LPItemContainer, @unchecked Sendable {
    var _children: NSMutableArray?

    @objc(initGroupWithTitle:andChildren:)
    init(groupWithTitle title: String?, andChildren children: [Any]?) {
        _children = NSMutableArray(capacity: 0)
        super.init(title: title)
        if let children {
            self.children.addObjects(from: children)
        }
    }

    @objc convenience init() {
        self.init(groupWithTitle: nil, andChildren: nil)
    }

    /// Decodes `title` after the `LPItem` columns.
    @objc(initWithSQLStatement:withColumn:)
    required init?(sqlStatement statement: OpaquePointer, withColumn column: UnsafeMutablePointer<Int32>) {
        super.init(sqlStatement: statement, withColumn: column)
        if let text = sqlite3_column_text(statement, column.pointee) {
            _title = String(cString: text)
        }
        column.pointee += 1
    }

    required init(forCopy: ()) {
        super.init(forCopy: ())
    }

    /// A deep copy also copies the children; their parent stays this group, not the copy.
    @objc(snapshotForStorage:deepCopy:)
    override func snapshotForStorage(_ forStorage: Bool, deepCopy: Bool) -> LPItem {
        let copy = super.snapshotForStorage(forStorage, deepCopy: deepCopy) as! LPGroup
        if deepCopy {
            let children = NSMutableArray(capacity: _children?.count ?? 0)
            for case let child as LPItem in _children ?? [] {
                let childCopy = child.snapshotForStorage(forStorage, deepCopy: true)
                childCopy.parentContainer = self
                children.add(childCopy)
            }
            copy._children = children
        }
        return copy
    }

    @objc override var isGroup: Bool { true }
    @objc var pagesOnly: Bool { true }

    /// No children, or only one empty page.
    @objc var isEmpty: Bool {
        let children = self.children
        if children.count == 1 {
            guard let page = children[0] as? LPPage else { return false }
            return page.isEmpty
        }
        return children.count == 0
    }

    // Flag bits of a folder: 0x1 auto-generated, 0x4 kind 1, 0x8 kind 2.

    @objc(_setValue:forFlag:)
    func _setValue(_ value: Bool, forFlag flag: UInt64) {
        let flags = self.flags
        guard (flag & ~flags != 0) == value else { return }
        self.flags = value ? flags | flag : flags & ~flag
    }

    @objc var autoGenerated: Bool {
        get { flags & 0x1 != 0 }
        set { _setValue(newValue, forFlag: 0x1) }
    }

    /// 2 for the TestFlight folder, 1 for the games folder, otherwise 0.
    @objc var kind: UInt {
        get { flags & 0x8 != 0 ? 2 : UInt(flags >> 2 & 1) }
        set {
            _setValue(newValue == 2, forFlag: 0x8)
            _setValue(newValue == 1, forFlag: 0x4)
        }
    }

    // MARK: Children

    @objc var children: NSMutableArray { mutableArrayValue(forKey: "synthesizedChildren") }
    @objc var storageChildren: NSArray { children }

    @objc func countOfSynthesizedChildren() -> UInt {
        UInt(_children?.count ?? 0)
    }

    @objc(objectInSynthesizedChildrenAtIndex:)
    func objectInSynthesizedChildren(at index: UInt) -> Any {
        _children![Int(index)]
    }

    @objc(insertObject:inSynthesizedChildrenAtIndex:)
    func insertObject(_ child: LPItem, inSynthesizedChildrenAt index: UInt) {
        let oldParent = child.parentContainer
        if pagesOnly {
            precondition(child is LPPage, "not allowed to insert a \(type(of: child)) into this container")
        }
        if _children == nil {
            _children = NSMutableArray(capacity: 0)
        }
        guard let children = _children else { return }
        if oldParent === self {
            children.removeObject(identicalTo: child)
            let index = min(Int(index), children.count)
            children.insert(child, at: index)
            reorderChild(child, inStorageOrder: index)
        } else {
            child.parentContainer = self
            children.insert(child, at: Int(index))
            if let oldParent {
                reparentChild(child, inStorageOrder: Int(index))
                // Progress and status label observers are added here in the original (phase 6).
                oldParent.children.remove(child)
            } else {
                insertNewChild(child, intoStorageWithOrder: Int(index))
            }
        }
    }

    @objc(removeObjectFromSynthesizedChildrenAtIndex:)
    func removeObjectFromSynthesizedChildren(at index: UInt) {
        guard let children = _children, Int(index) < children.count,
              let child = children[Int(index)] as? LPItem else { return }
        children.removeObject(at: Int(index))
        // The original recalculates the folder's progress and status label here (phase 6).
        if children.count == 0 {
            _children = nil
        }
        if child.parentContainer === self {
            if let group = child as? LPGroup {
                precondition(group.isEmpty, "It is illegal to delete an item from a group that is not empty")
            }
            child.parentContainer = nil
            deleteChildFromStorage(child)
        }
    }

    /// Calls `block` for every descendant, depth first; setting `stop` ends the current level.
    @objc(iterateChildren:)
    func iterateChildren(_ block: (LPItem, UnsafeMutablePointer<ObjCBool>) -> Void) {
        var stop: ObjCBool = false
        for case let child as LPItem in children {
            block(child, &stop)
            if stop.boolValue {
                return
            }
            if let group = child as? LPGroup {
                group.iterateChildren(block)
            }
        }
    }

    /// The first page with fewer than `maxCount` items; a new page at the end when none has room and
    /// `create` is set.
    @objc(firstAvailablePageWithMaxCount:createIfNecessary:)
    func firstAvailablePage(withMaxCount maxCount: UInt, createIfNecessary create: Bool) -> LPPage? {
        let pages = children
        var page = pages.firstObject as? LPPage
        while true {
            while let current = page {
                if UInt(current.children.count) < maxCount {
                    return current
                }
                let index = pages.indexOfObjectIdentical(to: current)
                guard index != NSNotFound, index + 1 < pages.count else { break }
                page = pages[index + 1] as? LPPage
            }
            guard create else { return nil }
            let newPage = LPPage(items: nil)
            pages.add(newPage)
            page = newPage
        }
    }
}

// MARK: - LPStorage

extension LPGroup {
    @objc override var storageType: Int { 2 }
    @objc override var storageTable: String? { "groups" }
    @objc override var storageCreationProperties: [String]? { ["title"] }

    /// Inserts the folder, then its children in order.
    @objc(insertIntoStorage:parent:withOrder:)
    override func insertIntoStorage(_ storage: AnyObject, parent parentUUID: String, withOrder order: Int) {
        super.insertIntoStorage(storage, parent: parentUUID, withOrder: order)
        guard let uuid else { return }
        for (index, child) in storageChildren.enumerated() {
            (child as? LPItem)?.insertIntoStorage(storage, parent: uuid, withOrder: index)
        }
    }
}
