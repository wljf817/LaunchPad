import Foundation
import Testing
@testable import LaunchPad

/// The item tree without a database (task 5.1).
@MainActor
struct ModelTreeTests {
    @Test func rootHidesItsHiddenPage() {
        let root = LPRoot()
        #expect(root.children.count == 0)
        #expect(root.storageChildren.count == 1)
        #expect(root.purgatory === root.storageChildren[0] as AnyObject)
        #expect(root.isEmpty)

        let page = LPPage(items: nil)
        root.children.add(page)
        #expect(root.children.count == 1)
        #expect(root.children[0] as AnyObject === page)
        #expect(root.storageChildren[1] as AnyObject === page)
        #expect(page.parentContainer === root)
        #expect(root.purgatory.parentContainer === root)

        root.children.removeObject(at: 0)
        #expect(root.children.count == 0)
        #expect(page.parentContainer == nil)
        #expect(root.storageChildren.count == 1)
    }

    @Test func parentsOfAnAppInAFolder() {
        let root = LPRoot()
        let page = LPPage(items: nil)
        root.children.add(page)
        let folderPage = LPPage(items: nil)
        let folder = LPGroup(groupWithTitle: "Folder", andChildren: [folderPage])
        page.children.add(folder)
        let app = makeTestApp("A")
        folderPage.children.add(app)

        #expect(app.parentContainer === folderPage)
        #expect(app.parentPage === folderPage)
        #expect(app.parentGroup === folder)
        #expect(app.root === root)
        #expect(folder.parentGroup == nil)
        #expect(folder.parentPage === page)
        #expect(!folder.isEmpty)
    }

    @Test func movingAnItemTakesItFromItsOldParent() {
        let first = LPPage(items: nil)
        let second = LPPage(items: nil)
        let apps = (0..<3).map { makeTestApp("A\($0)") }
        first.children.addObjects(from: apps)
        #expect(first.children.count == 3)

        second.children.add(apps[1])
        #expect(first.children as NSArray == [apps[0], apps[2]] as NSArray)
        #expect(second.children as NSArray == [apps[1]] as NSArray)
        #expect(apps[1].parentContainer === second)
    }

    @Test func reorderingWithinAParent() {
        let page = LPPage(items: nil)
        let apps = (0..<4).map { makeTestApp("A\($0)") }
        page.children.addObjects(from: apps)

        page.children.insert(apps[3], at: 0)
        #expect(page.children as NSArray == [apps[3], apps[0], apps[1], apps[2]] as NSArray)
        // An index past the end is clamped to the end.
        page.children.insert(apps[3], at: 4)
        #expect(page.children as NSArray == [apps[0], apps[1], apps[2], apps[3]] as NSArray)
        #expect(apps[3].parentContainer === page)
    }

    @Test func emptyFolders() {
        #expect(LPGroup().isEmpty)
        #expect(LPGroup(groupWithTitle: nil, andChildren: [LPPage(items: nil)]).isEmpty)
        let page = LPPage(items: [makeTestApp("A")])
        #expect(!LPGroup(groupWithTitle: nil, andChildren: [page]).isEmpty)
        #expect(!LPGroup(groupWithTitle: nil, andChildren: [LPPage(items: nil), LPPage(items: nil)]).isEmpty)
    }

    @Test func firstAvailablePage() throws {
        let folder = LPGroup()
        #expect(folder.firstAvailablePage(withMaxCount: 2, createIfNecessary: false) == nil)
        let created = try #require(folder.firstAvailablePage(withMaxCount: 2, createIfNecessary: true))
        #expect(folder.children as NSArray == [created] as NSArray)
        created.children.addObjects(from: [makeTestApp("A"), makeTestApp("B")])
        #expect(folder.firstAvailablePage(withMaxCount: 2, createIfNecessary: false) == nil)
        #expect(folder.firstAvailablePage(withMaxCount: 3, createIfNecessary: false) === created)
        let next = try #require(folder.firstAvailablePage(withMaxCount: 2, createIfNecessary: true))
        #expect(next !== created)
        #expect(folder.children.count == 2)
    }

    @Test func folderKindAndAutoGeneratedFlags() {
        let folder = LPGroup()
        folder.autoGenerated = true
        #expect(folder.flags == 0x1)
        folder.kind = 1
        #expect(folder.flags == 0x5)
        #expect(folder.kind == 1)
        folder.kind = 2
        #expect(folder.flags == 0x9)
        #expect(folder.kind == 2)
        folder.kind = 0
        #expect(folder.flags == 0x1)
        folder.autoGenerated = false
        #expect(folder.flags == 0)
    }

    @Test func iterateVisitsDescendantsDepthFirst() {
        let root = LPRoot()
        let page = LPPage(items: nil)
        root.children.add(page)
        let folderPage = LPPage(items: [makeTestApp("B")])
        let folder = LPGroup(groupWithTitle: "F", andChildren: [folderPage])
        page.children.addObjects(from: [makeTestApp("A"), folder, makeTestApp("C")])

        var visited: [String] = []
        root.iterateChildren { item, _ in
            visited.append(item.title ?? "page")
        }
        #expect(visited == ["page", "A", "F", "page", "B", "C"])

        // Stopping ends only the level it is set on.
        visited = []
        root.iterateChildren { item, stop in
            visited.append(item.title ?? "page")
            if item.title == "B" {
                stop.pointee = true
            }
        }
        #expect(visited == ["page", "A", "F", "page", "B", "C"])
    }

    @Test func purgatoryHoldsEachItemOnce() {
        let root = LPRoot()
        let app = makeTestApp("A")
        root.addItemToPurgatory(app)
        root.addItemToPurgatory(app)
        #expect(root.allPurgatoryItems.count == 1)
        #expect(app.parentContainer === root.purgatory)
        root.purgePurgatory()
        #expect(root.allPurgatoryItems.isEmpty)
        #expect(app.parentContainer == nil)
    }

    @Test func snapshotsKeepOrRenewTheUUID() {
        let app = makeTestApp("A", bundleID: "com.example.a")
        app._flags = 0x80
        let kept = app.snapshotForStorage(true, deepCopy: false) as! LPApp
        #expect(kept.uuid == app.uuid)
        #expect(kept.isSnapshot && kept.isSparseCopy)
        #expect(kept.title == "A" && kept.bundleIdentifier == "com.example.a" && kept.flags == 0x80)
        let renewed = app.snapshotForStorage(false, deepCopy: true)
        #expect(renewed.uuid != app.uuid)
        #expect(renewed.isSnapshot && !renewed.isSparseCopy)

        let folder = LPGroup(groupWithTitle: "F", andChildren: [LPPage(items: [app])])
        let copy = folder.snapshotForStorage(true, deepCopy: true) as! LPGroup
        let pageCopy = copy._children?[0] as! LPPage
        #expect(pageCopy.parentContainer === folder)
        #expect((pageCopy._children?[0] as! LPItem).uuid == app.uuid)
    }

    @Test func appsOnlyGoIntoPagesOfAFolder() async {
        await #expect(processExitsWith: .failure) {
            LPGroup().children.add(makeTestApp("A"))
        }
    }
}
